<?php

declare(strict_types=1);

namespace ForumKit\Core\Commands;

use ForumKit\Core\Schema\TableShape;
use Illuminate\Console\Command;

class DumpSchemaCommand extends Command
{
    protected $signature = 'forumkit:schema:dump
        {tables* : Base table names (without the prefix)}
        {--path= : Write to this file instead of printing}';

    protected $description = 'Print the exact structure of tables as a PHP snapshot for a package (for package authors)';

    public function handle(): int
    {
        $tables = [];

        foreach ((array) $this->argument('tables') as $base) {
            $tables[(string) $base] = TableShape::inspect((string) $base)->toArray();
        }

        $php = "<?php\n\ndeclare(strict_types=1);\n\n/*\n * The tables this package owns, exactly as an existing site has them. Generated by\n * `forumkit:schema:dump`; used by `forumkit:adopt` and by the package's parity tests.\n */\n\nreturn ".$this->export(['tables' => $tables]).";\n";

        $path = $this->option('path');

        if (is_string($path) && $path !== '') {
            file_put_contents($path, $php);
            $this->info("Wrote {$path}");

            return self::SUCCESS;
        }

        $this->line($php);

        return self::SUCCESS;
    }

    /**
     * Export a value as PHP source using short array syntax and four-space indentation.
     */
    private function export(mixed $value, int $depth = 0): string
    {
        if ($value === null) {
            return 'null';
        }

        if (! is_array($value)) {
            return var_export($value, true);
        }

        if ($value === []) {
            return '[]';
        }

        $pad = str_repeat('    ', $depth + 1);
        $isList = array_is_list($value);
        $lines = [];

        foreach ($value as $key => $item) {
            $prefix = $isList ? '' : var_export($key, true).' => ';
            $lines[] = $pad.$prefix.$this->export($item, $depth + 1).',';
        }

        return "[\n".implode("\n", $lines)."\n".str_repeat('    ', $depth).']';
    }
}
