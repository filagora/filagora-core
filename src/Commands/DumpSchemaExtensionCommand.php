<?php

declare(strict_types=1);

namespace ForumKit\Core\Commands;

use ForumKit\Core\Schema\SchemaRegistry;
use ForumKit\Core\Schema\TableShape;
use Illuminate\Console\Command;

class DumpSchemaExtensionCommand extends Command
{
    protected $signature = 'forumkit:schema:dump-extension
        {module : The package whose tables are extended (for example forums)}
        {tables* : Base table names (without the prefix)}
        {--path= : Write to this file instead of printing}';

    protected $description = 'Print what tables carry beyond a package\'s own snapshot, as a schema extension (for profile package authors)';

    public function handle(SchemaRegistry $registry): int
    {
        $module = (string) $this->argument('module');
        $schema = $registry->get($module);

        if ($schema === null) {
            $this->error("No schema snapshot is registered for module [{$module}].");

            return self::FAILURE;
        }

        $tables = [];

        foreach ((array) $this->argument('tables') as $base) {
            $base = (string) $base;

            if (! isset($schema->tables[$base])) {
                $this->error("Module [{$module}] does not own table [{$base}].");

                return self::FAILURE;
            }

            try {
                $actual = TableShape::inspect($base);
            } catch (\InvalidArgumentException $e) {
                $this->error($e->getMessage().' Run the migrations first.');

                return self::FAILURE;
            }

            $extras = $actual->extrasOver($schema->tables[$base]);
            $extras = array_filter($extras, fn (array $part): bool => $part !== []);

            if ($extras !== []) {
                $tables[$base] = $extras;
            }
        }

        $php = "<?php\n\ndeclare(strict_types=1);\n\n/*\n * What these tables carry beyond the `{$module}` package's own snapshot. Generated by\n * `forumkit:schema:dump-extension`; register it with SchemaExtension::fromFile().\n */\n\nreturn ".SchemaDumper::export(['tables' => $tables]).";\n";

        $path = $this->option('path');

        if (is_string($path) && $path !== '') {
            file_put_contents($path, $php);
            $this->info("Wrote {$path}");

            return self::SUCCESS;
        }

        $this->line($php);

        return self::SUCCESS;
    }
}
